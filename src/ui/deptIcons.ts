/**
 * The departments in groups, in the panel's order. A department not in `DEPT_GROUPS` (a new
 * stop) lands in a last group, More, so it still shows.
 */
export function groupDepts<D extends { id: string }>(
  depts: D[],
): { title: string; depts: D[] }[] {
  const byId = new Map(depts.map((d) => [d.id, d]));
  const out = DEPT_GROUPS.map((g) => ({
    title: g.title,
    depts: g.ids.map((id) => byId.get(id)).filter((d): d is D => !!d),
  }));
  const known = new Set([...DEPT_GROUPS.flatMap((g) => g.ids), ...CAMERA_VIEW_IDS, ...RIDE_IDS, ...NIGHT_IDS]);
  const rest = depts.filter((d) => !known.has(d.id));
  if (rest.length) out.push({ title: "More", depts: rest });
  return out.filter((g) => g.depts.length);
}

/** The departments in the panel's order (for the keys 1–9, 0). */
export function orderDepts<D extends { id: string }>(depts: D[]): D[] {
  return groupDepts(depts).flatMap((g) => g.depts);
}
